import { expect, test } from "@playwright/test";
import { askMorph, demoLogin } from "./helpers";

test("unauthenticated visitors are redirected to sign in", async ({ page }) => {
  await page.goto("/studio");
  await expect(page).toHaveURL(/\/login/);
  await expect(page.getByRole("heading", { name: "Welcome back" })).toBeVisible();
});

test("demo account opens a personalized, populated workspace", async ({ page }) => {
  await demoLogin(page);
  await expect(page.getByRole("heading", { name: "Revenue command center" })).toBeVisible();
  // Live data and the honest engine label are both present.
  await expect(page.getByText("Pipeline value").first()).toBeVisible();
  await expect(page.getByText("Local planner").first()).toBeVisible();
  await expect(page.getByText(/Rendered from a validated schema/)).toBeVisible();
});

test("natural-language transformation previews, applies and undoes", async ({ page }) => {
  await demoLogin(page);
  await askMorph(page, "Show team workload, unfinished tasks, and bottlenecks.");

  await expect(page.getByText("Preview — not applied")).toBeVisible({ timeout: 30_000 });
  await expect(page.getByText("Operations control room").first()).toBeVisible();
  await expect(page.getByText(/preserved/).first()).toBeVisible();

  await page.getByRole("button", { name: "Apply change" }).click();
  await expect(page.getByText("Preview — not applied")).toHaveCount(0);
  await expect(page.getByRole("heading", { name: "Operations control room" })).toBeVisible();

  await page.getByRole("button", { name: "Undo" }).click();
  await expect(page.getByRole("heading", { name: "Revenue command center" })).toBeVisible();
});

test("Morph refuses requests outside its capability instead of faking success", async ({ page }) => {
  await demoLogin(page);
  await askMorph(page, "Delete every lead in the database and email the whole team.");
  await expect(page.getByText("Not applied")).toBeVisible({ timeout: 30_000 });
  await expect(page.getByText(/no capability to delete data/i).first()).toBeVisible();
});

test("CRM records are created and persist through a reload", async ({ page }) => {
  await demoLogin(page);
  await page.goto("/studio/crm/leads");
  const uniqueName = `E2E Lead ${Date.now().toString().slice(-6)}`;

  await page.getByRole("button", { name: "New lead" }).first().click();
  await page.getByLabel("Name", { exact: true }).fill(uniqueName);
  await page.getByLabel("Company", { exact: true }).fill("Kestrel Systems");
  await page.getByRole("button", { name: "Create lead" }).click();
  await expect(page.getByText("Lead created")).toBeVisible({ timeout: 20_000 });

  await page.getByLabel("Search table").fill(uniqueName);
  await expect(page.getByRole("cell", { name: uniqueName })).toBeVisible();

  await page.reload();
  await page.getByLabel("Search table").fill(uniqueName);
  await expect(page.getByRole("cell", { name: uniqueName })).toBeVisible();
});

test("a workflow executes a real action and logs the run", async ({ page }) => {
  await demoLogin(page);
  await page.goto("/studio/workflows");
  await expect(page.getByText("Stale lead follow-up").first()).toBeVisible();

  await page.getByRole("button", { name: "Run now" }).first().click();
  await expect(page.getByText(/Workflow executed|Skipped/).first()).toBeVisible({ timeout: 30_000 });

  await page.getByRole("button", { name: /Execution history/ }).click();
  await expect(page.getByRole("cell", { name: "Stale lead follow-up" }).first()).toBeVisible();
});

test("before/after demo generates a real interface and can be reset", async ({ page }) => {
  await demoLogin(page);
  await page.goto("/studio/compare");

  await expect(page.getByText("Before · classic CRM")).toBeVisible();
  await page.getByRole("button", { name: /Demo A · Sales manager/ }).click();
  await page.getByRole("button", { name: "Generate live interface" }).click();

  await expect(page.getByText(/generated by/i)).toBeVisible({ timeout: 40_000 });
  await expect(page.getByText("After · Sales manager")).toBeVisible();

  await page.getByRole("button", { name: "Reset demo" }).click();
  await expect(page.getByText("Demo reset")).toBeVisible({ timeout: 20_000 });
});

test("a new account completes onboarding and lands in a seeded workspace", async ({ page }) => {
  const email = `founder+${Date.now()}@morph.test`;
  await page.goto("/signup");
  await page.getByLabel("Full name").fill("Ada Founder");
  await page.getByLabel("Work email").fill(email);
  await page.getByLabel("Password").fill("supersecret123");
  await page.getByRole("button", { name: "Create account" }).click();

  await expect(page.getByRole("heading", { name: /what do you do/i })).toBeVisible({ timeout: 30_000 });
  await page.getByRole("button", { name: /Sales representative/ }).click();
  await page.getByRole("button", { name: "Continue" }).click();
  await page.getByRole("button", { name: "Hit my monthly number" }).click();
  await page.getByRole("button", { name: "Continue" }).click();
  await page.getByRole("button", { name: "Build my workspace" }).click();

  await expect(page).toHaveURL(/\/studio/, { timeout: 40_000 });
  await expect(page.getByRole("heading", { name: "My day" })).toBeVisible();
  // The new account sees only its own workspace data.
  await page.goto("/studio/crm/leads");
  await expect(page.getByRole("heading", { name: "Leads" })).toBeVisible();
});

test("version history restores an earlier layout", async ({ page }) => {
  await demoLogin(page);
  await askMorph(page, "I want a simple workspace focused on my assigned leads and today's tasks.");
  await expect(page.getByText("Preview — not applied")).toBeVisible({ timeout: 30_000 });
  await page.getByRole("button", { name: "Apply change" }).click();
  await expect(page.getByRole("heading", { name: "My day" })).toBeVisible();

  await page.goto("/studio/versions");
  await expect(page.getByRole("heading", { name: "Version history" })).toBeVisible();
  await page.getByRole("button", { name: "Restore" }).first().click();
  await expect(page.getByText(/Restored v/)).toBeVisible({ timeout: 20_000 });

  await page.goto("/studio");
  await expect(page.getByRole("heading", { name: "Revenue command center" })).toBeVisible();
});
