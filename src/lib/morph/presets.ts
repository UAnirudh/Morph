const PRESETS: Record<JobRole, ConfigInput> = {
  sales_manager: SALES_MANAGER_INPUT,
  sales_rep: SALES_REP_INPUT,
  ops_manager: OPS_MANAGER_INPUT,
  general: GENERAL_INPUT,
};

export function rolePresetConfig(role: JobRole): MorphConfig {
  return morphConfigSchema.parse(structuredClone(PRESETS[role] ?? GENERAL_INPUT));
}

export function rolePresetSummary(role: JobRole): string {
  const config = rolePresetConfig(role);
  return config.description ?? config.name;
}

