const nav = (
  id: string,
  label: string,
  href: NavigationItem["href"],
  icon: NavigationItem["icon"],
  badge?: NavigationItem["badge"],
): NavigationItem => ({ id, label, href, icon, badge });

const metric = (
  id: string,
  m: string,
  opts: Partial<Extract<MorphComponent, { type: "metric" }>> = {},
): MorphComponent =>
  ({
    type: "metric",
    id,
    metric: m,
    span: 3,
    group: "overview",
    title: undefined,
    ...opts,
  }) as MorphComponent;

