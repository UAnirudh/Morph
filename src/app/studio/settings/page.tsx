import type { Metadata } from "next";
import { getDb } from "@/lib/db";
import { getWorkspaceContext } from "@/lib/auth/session";
import { getAccessibility, getPreferencesGoals } from "@/lib/auth/session";
import { recentAiUsage } from "@/lib/morph/engine";
import { providerModel } from "@/lib/morph/provider";
import { ROLE_LABELS, type JobRole } from "@/lib/morph/config";
import { Badge } from "@/components/ui/badge";
import { Separator } from "@/components/ui/badge";
import { SettingsForm } from "@/components/studio/settings-form";
import { formatDate, formatNumber } from "@/lib/utils";

export const metadata: Metadata = { title: "Settings" };
export const dynamic = "force-dynamic";

export default async function SettingsPage() {
  const ctx = await getWorkspaceContext({ requireOnboarded: true });
  const db = getDb();
  const accessibility = getAccessibility(ctx.preferences);
  const usage = recentAiUsage(db, ctx.workspace.id);
  const providerConfigured = Boolean(process.env.OPENAI_API_KEY);

  const transformations = db
    .prepare("SELECT COUNT(*) AS c FROM transformation_requests WHERE workspace_id = ? AND status = 'applied'")
    .get(ctx.workspace.id) as { c: number };
  const rejected = db
    .prepare("SELECT COUNT(*) AS c FROM transformation_requests WHERE workspace_id = ? AND status = 'rejected'")
    .get(ctx.workspace.id) as { c: number };

  return (
    <div className="px-4 py-5 lg:px-6">
      <header>
        <h1 className="text-lg font-semibold tracking-tight">Settings</h1>
        <p className="mt-0.5 max-w-2xl text-xs text-muted-foreground">
          Explicit preferences Morph uses when planning, plus the operational state of this deployment.
        </p>
      </header>

      <div className="mt-4 grid gap-4 xl:grid-cols-[1.4fr_1fr]">
        <SettingsForm
          initial={{
            jobRole: ctx.preferences.job_role as JobRole,
            goals: getPreferencesGoals(ctx.preferences),
            density: ctx.preferences.density,
            fontSize: accessibility.fontSize ?? "base",
            highContrast: accessibility.highContrast ?? false,
            reduceMotion: accessibility.reduceMotion ?? false,
            reduceClutter: accessibility.reduceClutter ?? false,
          }}
        />

        <div className="space-y-4">
          <section className="rounded-xl border border-border/70 bg-card/60 p-4">
            <h2 className="text-sm font-semibold">Account</h2>
            <dl className="mt-2 space-y-2 text-xs">
              <div className="flex items-center justify-between gap-2">
                <dt className="text-muted-foreground">Name</dt>
                <dd className="font-medium">{ctx.user.name}</dd>
              </div>
              <div className="flex items-center justify-between gap-2">
                <dt className="text-muted-foreground">Email</dt>
                <dd className="truncate font-medium">{ctx.user.email}</dd>
              </div>
              <div className="flex items-center justify-between gap-2">
                <dt className="text-muted-foreground">Role</dt>
                <dd className="font-medium">{ROLE_LABELS[ctx.preferences.job_role as JobRole]}</dd>
              </div>
              <div className="flex items-center justify-between gap-2">
                <dt className="text-muted-foreground">Workspace</dt>
                <dd className="truncate font-medium">{ctx.workspace.name}</dd>
              </div>
              <div className="flex items-center justify-between gap-2">
                <dt className="text-muted-foreground">Member since</dt>
                <dd className="font-medium">{formatDate(ctx.workspace.created_at)}</dd>
              </div>
            </dl>
          </section>

          <section className="rounded-xl border border-border/70 bg-card/60 p-4">
            <div className="flex items-center justify-between gap-2">
              <h2 className="text-sm font-semibold">Morph Engine</h2>
              <Badge tone={providerConfigured ? "success" : "warning"}>
                {providerConfigured ? "Live model" : "Local planner"}
              </Badge>
            </div>
            <p className="mt-1 text-[11px] leading-relaxed text-muted-foreground">
              {providerConfigured
                ? `Proposals are generated by ${providerModel()} with structured JSON output, Zod validation and one repair attempt.`
                : "No OPENAI_API_KEY is configured, so proposals come from the deterministic local planner. The UI always labels the engine that produced a change."}
            </p>
            <Separator className="my-3" />
            <dl className="grid grid-cols-2 gap-2 text-xs">
              <div>
                <dt className="text-[10px] uppercase tracking-wider text-muted-foreground">Applied</dt>
                <dd className="mt-0.5 text-base font-semibold tabular-nums">{formatNumber(transformations.c)}</dd>
              </div>
              <div>
                <dt className="text-[10px] uppercase tracking-wider text-muted-foreground">Rejected</dt>
                <dd className="mt-0.5 text-base font-semibold tabular-nums">{formatNumber(rejected.c)}</dd>
              </div>
            </dl>
          </section>

          <section className="rounded-xl border border-border/70 bg-card/60 p-4">
            <h2 className="text-sm font-semibold">AI usage (30 days)</h2>
            {usage.length === 0 ? (
              <p className="mt-1 text-[11px] text-muted-foreground">No transformations recorded yet.</p>
            ) : (
              <table className="mt-2 w-full text-left text-[11px]">
                <thead>
                  <tr className="text-[10px] uppercase tracking-wider text-muted-foreground">
                    <th className="py-1">Engine</th>
                    <th className="py-1">Requests</th>
                    <th className="py-1">Tokens</th>
                    <th className="py-1">Avg ms</th>
                  </tr>
                </thead>
                <tbody>
                  {usage.map((row) => (
                    <tr key={`${row.engine}-${row.model}`} className="border-t border-border/40">
                      <td className="py-1">{row.model ?? row.engine}</td>
                      <td className="py-1 tabular-nums">{row.requests}</td>
                      <td className="py-1 tabular-nums">
                        {formatNumber((row.inputTokens ?? 0) + (row.outputTokens ?? 0))}
                      </td>
                      <td className="py-1 tabular-nums">{Math.round(row.avgLatency ?? 0)}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            )}
            <p className="mt-2 text-[10px] leading-relaxed text-muted-foreground">
              Usage is recorded per workspace for budget tracking. The local planner records zero tokens
              because it makes no model call.
            </p>
          </section>
        </div>
      </div>
    </div>
  );
}
